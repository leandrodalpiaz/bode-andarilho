-- Bode Andarilho PWA v2
-- Esta migration é aditiva e deliberadamente não toca nas tabelas legadas.
-- Aplicar somente em um ambiente isolado após validação pelo Supabase CLI.

create schema if not exists pwa_v2;
create schema if not exists pwa_private;

revoke all on schema pwa_v2 from public;
grant usage on schema pwa_v2 to anon, authenticated, service_role;

revoke all on schema pwa_private from public;
grant usage on schema pwa_private to authenticated, service_role;

create table if not exists pwa_v2.perfis (
    id uuid primary key default extensions.gen_random_uuid(),
    auth_user_id uuid unique references auth.users(id) on delete set null,
    nome text not null check (char_length(btrim(nome)) between 2 and 160),
    email text not null check (position('@' in email) > 1),
    telefone text,
    status text not null default 'active'
        check (status in ('invited', 'pending', 'active', 'suspended')),
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

create unique index if not exists perfis_email_lower_uidx
    on pwa_v2.perfis (lower(email));

create table if not exists pwa_v2.identidades_externas (
    id bigint generated by default as identity primary key,
    perfil_id uuid not null references pwa_v2.perfis(id) on delete cascade,
    provedor text not null check (provedor in ('telegram', 'whatsapp', 'instagram', 'outro')),
    external_user_id text not null check (char_length(btrim(external_user_id)) between 1 and 240),
    metadata jsonb not null default '{}'::jsonb,
    created_at timestamptz not null default now(),
    unique (provedor, external_user_id),
    unique (perfil_id, provedor)
);

create table if not exists pwa_v2.lojas (
    id bigint generated by default as identity primary key,
    nome text not null check (char_length(btrim(nome)) between 2 and 180),
    slug text not null check (slug ~ '^[a-z0-9]+(?:-[a-z0-9]+)*$'),
    numero_loja text,
    descricao text,
    cidade text,
    uf text check (uf is null or char_length(uf) between 2 and 3),
    endereco text,
    rito text,
    potencia text,
    potencia_complemento text,
    instagram_handle text,
    logo_path text,
    template_card_path text,
    layout_config jsonb not null default '{}'::jsonb,
    status text not null default 'active'
        check (status in ('draft', 'active', 'archived')),
    created_by uuid references pwa_v2.perfis(id) on delete set null,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    unique (slug)
);

create table if not exists pwa_v2.vinculos_loja (
    id bigint generated by default as identity primary key,
    perfil_id uuid not null references pwa_v2.perfis(id) on delete cascade,
    loja_id bigint references pwa_v2.lojas(id) on delete cascade,
    papel text not null check (papel in ('member', 'secretary', 'admin')),
    status text not null default 'active'
        check (status in ('invited', 'active', 'inactive')),
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    check (loja_id is not null or papel = 'admin'),
    unique (perfil_id, loja_id, papel)
);

create unique index if not exists vinculos_admin_global_uidx
    on pwa_v2.vinculos_loja (perfil_id)
    where loja_id is null and papel = 'admin';

create table if not exists pwa_v2.convites_conta (
    id uuid primary key default extensions.gen_random_uuid(),
    token_hash text not null unique,
    email_autorizado text not null check (position('@' in email_autorizado) > 1),
    papel text not null check (papel in ('member', 'secretary', 'admin')),
    loja_id bigint references pwa_v2.lojas(id) on delete cascade,
    valid_until timestamptz not null,
    consumed_at timestamptz,
    consumed_by_profile_id uuid references pwa_v2.perfis(id) on delete set null,
    created_by_profile_id uuid references pwa_v2.perfis(id) on delete set null,
    created_at timestamptz not null default now(),
    check (loja_id is not null or papel = 'admin'),
    check ((consumed_at is null) = (consumed_by_profile_id is null))
);

create table if not exists pwa_v2.eventos (
    id bigint generated by default as identity primary key,
    loja_id bigint not null references pwa_v2.lojas(id) on delete restrict,
    criado_por_id uuid not null references pwa_v2.perfis(id) on delete restrict,
    secretario_id uuid references pwa_v2.perfis(id) on delete set null,
    secretario_snapshot_nome text,
    evento_at timestamptz not null,
    titulo text not null check (char_length(btrim(titulo)) between 2 and 160),
    descricao text,
    status text not null default 'draft'
        check (status in ('draft', 'published', 'cancelled', 'closed')),
    visibilidade text not null default 'private'
        check (visibilidade in ('private', 'public')),
    public_token_hash text not null unique,
    idempotency_key_hash text not null,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    unique (loja_id, idempotency_key_hash)
);

create table if not exists pwa_v2.solicitacoes_presenca (
    id bigint generated by default as identity primary key,
    evento_id bigint not null references pwa_v2.eventos(id) on delete cascade,
    perfil_id uuid references pwa_v2.perfis(id) on delete set null,
    visitante_nome text not null check (char_length(btrim(visitante_nome)) between 2 and 160),
    visitante_email text,
    visitante_telefone text,
    agape text not null default 'sem' check (agape in ('sem', 'com', 'gratuito', 'pago')),
    status text not null default 'pending'
        check (status in ('pending', 'approved', 'rejected', 'cancelled')),
    origem text not null default 'public'
        check (origem in ('public', 'pwa', 'telegram', 'admin')),
    idempotency_key_hash text not null,
    recibo_hash text not null unique,
    revisado_por_id uuid references pwa_v2.perfis(id) on delete set null,
    revisado_at timestamptz,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    unique (evento_id, idempotency_key_hash),
    check (visitante_email is null or position('@' in visitante_email) > 1)
