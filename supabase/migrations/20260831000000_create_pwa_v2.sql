create or replace function pwa_private.current_profile_id()
returns uuid
language sql
stable
security definer
set search_path = pwa_v2, pg_catalog
as $$
    select p.id
      from pwa_v2.perfis as p
     where p.auth_user_id = auth.uid()
     limit 1
$$;

create or replace function pwa_private.is_global_admin()
returns boolean
language sql
stable
security definer
set search_path = pwa_v2, pg_catalog
as $$
    select exists (
        select 1
          from pwa_v2.vinculos_loja as v
         where v.perfil_id = pwa_private.current_profile_id()
           and v.loja_id is null
           and v.papel = 'admin'
           and v.status = 'active'
    )
$$;

create or replace function pwa_private.has_store_role(target_store_id bigint, allowed_roles text[])
returns boolean
language sql
stable
security definer
set search_path = pwa_v2, pg_catalog
as $$
    select pwa_private.is_global_admin()
        or exists (
            select 1
              from pwa_v2.vinculos_loja as v
             where v.perfil_id = pwa_private.current_profile_id()
               and v.loja_id = target_store_id
               and v.papel = any(allowed_roles)
               and v.status = 'active'
        )
$$;

create or replace function pwa_private.consume_invite(
    invite_token_hash text,
    target_auth_user_id uuid,
    authenticated_email text,
    request_uuid uuid
)
returns jsonb
language plpgsql
security definer
set search_path = pwa_v2, pg_catalog
as $$
declare
    invite_row pwa_v2.convites_conta%rowtype;
    target_profile_id uuid;
    display_name text;
begin
    if invite_token_hash is null or target_auth_user_id is null or authenticated_email is null then
        raise exception using errcode = '22023', message = 'Dados de convite incompletos';
    end if;

    select *
      into invite_row
      from pwa_v2.convites_conta
     where token_hash = invite_token_hash
     for update;

    if not found then
        raise exception using errcode = 'P0001', message = 'Convite inválido';
    end if;
    if invite_row.consumed_at is not null then
        raise exception using errcode = 'P0001', message = 'Convite já consumido';
    end if;
    if invite_row.valid_until <= now() then
        raise exception using errcode = 'P0001', message = 'Convite expirado';
    end if;
    if lower(btrim(invite_row.email_autorizado)) <> lower(btrim(authenticated_email)) then
        raise exception using errcode = 'P0001', message = 'E-mail não autorizado para este convite';
    end if;

    display_name := split_part(lower(btrim(authenticated_email)), '@', 1);
    select p.id
      into target_profile_id
      from pwa_v2.perfis as p
     where p.auth_user_id = target_auth_user_id
     for update;

    if target_profile_id is null then
        insert into pwa_v2.perfis (auth_user_id, nome, email, status)
        values (target_auth_user_id, display_name, lower(btrim(authenticated_email)), 'active')
        returning id into target_profile_id;
    else
        update pwa_v2.perfis
           set email = lower(btrim(authenticated_email)),
               status = 'active',
               updated_at = now()
         where id = target_profile_id;
    end if;

    insert into pwa_v2.vinculos_loja (perfil_id, loja_id, papel, status)
    values (target_profile_id, invite_row.loja_id, invite_row.papel, 'active')
    on conflict (perfil_id, loja_id, papel)
    do update set status = 'active', updated_at = now();

    update pwa_v2.convites_conta
       set consumed_at = now(), consumed_by_profile_id = target_profile_id
     where id = invite_row.id;

    insert into pwa_v2.auditoria (
        ator_perfil_id, acao, entidade_tipo, entidade_id, origem, request_id, metadata
    ) values (
        target_profile_id, 'invite_consumed', 'convites_conta', invite_row.id::text, 'bootstrap', request_uuid,
        jsonb_build_object('papel', invite_row.papel, 'loja_id', invite_row.loja_id)
    );

    return jsonb_build_object(
        'perfil_id', target_profile_id,
        'loja_id', invite_row.loja_id,
        'papel', invite_row.papel
    );
end
$$;

create or replace function pwa_private.bootstrap_admin(
    target_auth_user_id uuid,
    authenticated_email text,
    display_name text,
    request_uuid uuid
)
returns jsonb
language plpgsql
security definer
set search_path = pwa_v2, pg_catalog
as $$
declare
    target_profile_id uuid;
begin
    if target_auth_user_id is null or authenticated_email is null then
        raise exception using errcode = '22023', message = 'Dados do administrador incompletos';
    end if;
    if exists (
        select 1 from pwa_v2.vinculos_loja
         where loja_id is null and papel = 'admin' and status = 'active'
    ) then
        raise exception using errcode = 'P0001', message = 'Administrador inicial já configurado';
    end if;

    select p.id into target_profile_id
      from pwa_v2.perfis p
     where p.auth_user_id = target_auth_user_id
     for update;

    if target_profile_id is null then
        insert into pwa_v2.perfis (auth_user_id, nome, email, status)
        values (
            target_auth_user_id,
            coalesce(nullif(btrim(display_name), ''), split_part(lower(btrim(authenticated_email)), '@', 1)),
            lower(btrim(authenticated_email)),
            'active'
        )
        returning id into target_profile_id;
    else
        update pwa_v2.perfis
           set nome = coalesce(nullif(btrim(display_name), ''), nome),
               email = lower(btrim(authenticated_email)),
               status = 'active',
               updated_at = now()
         where id = target_profile_id;
    end if;

    insert into pwa_v2.vinculos_loja (perfil_id, loja_id, papel, status)
    values (target_profile_id, null, 'admin', 'active');

    insert into pwa_v2.auditoria (
        ator_perfil_id, acao, entidade_tipo, entidade_id, origem, request_id, metadata
    ) values (
        target_profile_id, 'admin_bootstrapped', 'perfis', target_profile_id::text, 'bootstrap', request_uuid, '{}'::jsonb
    );

    return jsonb_build_object('perfil_id', target_profile_id, 'papel', 'admin');
end
$$;

